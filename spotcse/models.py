class MLPLayer(nn.Module):
    """
    Head for getting sentence representations over RoBERTa/BERT's CLS representation.
    """

    def __init__(self, config):
        super().__init__()
        self.dense = nn.Linear(config.hidden_size, config.hidden_size)
        self.activation = nn.Tanh()

    def forward(self, features, **kwargs):
        x = self.dense(features)
        x = self.activation(x)

        return x

class Similarity(nn.Module):
    """
    Dot product or cosine similarity
    """

    def __init__(self, temp):
        super().__init__()
        self.temp = temp
        self.cos = nn.CosineSimilarity(dim=-1)

    def forward(self, x, y):
        return self.cos(x, y) / self.temp


class PowerIterationSinkhornLoss(nn.Module):
    def __init__(
        self,
        top_k=5,
        power_iterations=5,
        direction_weight=0.5,
        target_lambda=1,
        sinkhorn_temperature=0.05,
        sinkhorn_iterations=5,
        sinkhorn_eps=1e-8,
        prediction_temperature=0.07,
    ):
        super().__init__()
        self.top_k = top_k
        self.power_iterations = power_iterations
        self.direction_weight = direction_weight
        self.target_lambda = target_lambda
        self.sinkhorn_temperature = sinkhorn_temperature
        self.sinkhorn_iterations = sinkhorn_iterations
        self.sinkhorn_eps = sinkhorn_eps
        self.prediction_temperature = prediction_temperature
        self.last_target_diff_mse = None
        self.capture_matrices = False
        self.captured_matrices = None

    def _top_directions(self, x):
        x = x.float()
        batch_size, hidden_size = x.shape
        num_directions = min(self.top_k, batch_size, hidden_size)
        directions = torch.randn(
            hidden_size,
            num_directions,
            device=x.device,
            dtype=x.dtype,
        )
        directions, _ = torch.linalg.qr(directions.float(), mode="reduced")

        gram = (x.transpose(0, 1) @ x).float()
        for _ in range(self.power_iterations):
            directions, _ = torch.linalg.qr(
                (gram @ directions).float(),
                mode="reduced",
            )
        return directions

    def forward(self, x1, x2):
        x1 = F.normalize(x1 - x1.mean(dim=0, keepdim=True), dim=-1)
        x2 = F.normalize(x2 - x2.mean(dim=0, keepdim=True), dim=-1)
        similarity = x1 @ x2.transpose(0, 1)

        with torch.no_grad(), torch.cuda.amp.autocast(enabled=False):
            target_x1 = x1.detach().float()
            target_x2 = x2.detach().float()
            # Use only X_1^T X_1 to estimate the feature-space directions.
            directions = self._top_directions(target_x1)
            direction_similarity = (
                (target_x1 @ directions)
                @ (target_x2 @ directions).transpose(0, 1)
            )
            kernel_logits = (
                target_x1 @ target_x2.transpose(0, 1)
                - self.direction_weight * direction_similarity
            ) / self.sinkhorn_temperature
            # A global shift leaves Sinkhorn scaling unchanged and avoids overflow.
            kernel = torch.exp(kernel_logits - kernel_logits.max())

            batch_size = similarity.size(0)
            u = torch.ones(
                batch_size, 1, device=kernel.device, dtype=kernel.dtype
            )
            v = torch.ones_like(u)
            for _ in range(self.sinkhorn_iterations):
                u = 1.0 / (kernel @ v + self.sinkhorn_eps)
                v = 1.0 / (kernel.transpose(0, 1) @ u + self.sinkhorn_eps)

            sinkhorn_target = u * kernel * v.transpose(0, 1)
            identity = torch.eye(
                batch_size, device=kernel.device, dtype=kernel.dtype
            )
            target = (
                (1.0 - self.target_lambda) * identity
                + self.target_lambda * sinkhorn_target
            )

            diff = target - torch.eye(target.size(0), device=target.device, dtype=target.dtype)
            self.last_target_diff_mse = diff.pow(2).mean().detach()

            if self.capture_matrices:
                self.captured_matrices = {
                    "target_x1": target_x1.detach().float().cpu(),
                    "similarity": similarity.detach().float().cpu(),
                    "direction_similarity": direction_similarity.detach().float().cpu(),
                    "kernel_logits": kernel_logits.detach().float().cpu(),
                    "sinkhorn_target": sinkhorn_target.detach().float().cpu(),
                }

        log_prediction = F.log_softmax(
            similarity / self.prediction_temperature,
            dim=-1,
        )
        loss = -(target * log_prediction).sum(dim=-1).mean()
        return loss, similarity


class Pooler(nn.Module):
    """
    Parameter-free poolers to get the sentence embedding
    'cls': [CLS] representation with BERT/RoBERTa's MLP pooler.
    'cls_before_pooler': [CLS] representation without the original MLP pooler.
    'avg': average of the last layers' hidden states at each token.
    'avg_top2': average of the last two layers.
    'avg_first_last': average of the first and the last layers.
    """
    def __init__(self, pooler_type):
        super().__init__()
        self.pooler_type = pooler_type
        assert self.pooler_type in ["cls", "cls_before_pooler", "avg", "avg_top2", "avg_first_last"], "unrecognized pooling type %s" % self.pooler_type

    def forward(self, attention_mask, outputs):
        last_hidden = outputs.last_hidden_state
        pooler_output = outputs.pooler_output
        hidden_states = outputs.hidden_states

        if self.pooler_type in ['cls_before_pooler', 'cls']:
            return last_hidden[:, 0]
        elif self.pooler_type == "avg":
            return ((last_hidden * attention_mask.unsqueeze(-1)).sum(1) / attention_mask.sum(-1).unsqueeze(-1))
        elif self.pooler_type == "avg_first_last":
            first_hidden = hidden_states[1]
            last_hidden = hidden_states[-1]
            pooled_result = ((first_hidden + last_hidden) / 2.0 * attention_mask.unsqueeze(-1)).sum(1) / attention_mask.sum(-1).unsqueeze(-1)
            return pooled_result
        elif self.pooler_type == "avg_top2":
            second_last_hidden = hidden_states[-2]
            last_hidden = hidden_states[-1]
            pooled_result = ((last_hidden + second_last_hidden) / 2.0 * attention_mask.unsqueeze(-1)).sum(1) / attention_mask.sum(-1).unsqueeze(-1)
            return pooled_result
        else:
            raise NotImplementedError


def cl_init(cls, config):
    """
    Contrastive learning class init function.
    """
    cls.pooler_type = cls.model_args.pooler_type
    cls.pooler = Pooler(cls.model_args.pooler_type)
    if cls.model_args.pooler_type == "cls":
        cls.mlp = MLPLayer(config)
    cls.sim = Similarity(temp=cls.model_args.temp)
    cls.loss_fct = PowerIterationSinkhornLoss(
        top_k=cls.model_args.top_k,
        direction_weight=cls.model_args.direction_weight,
        sinkhorn_temperature=cls.model_args.sinkhorn_temp,
        prediction_temperature=cls.model_args.pred_temp,
    )
    cls.init_weights()

def cl_forward(cls,
    encoder,
    input_ids=None,
    attention_mask=None,
    token_type_ids=None,
    position_ids=None,
    head_mask=None,
    inputs_embeds=None,
    labels=None,
    output_attentions=None,
    output_hidden_states=None,
    return_dict=None,
    mlm_input_ids=None,
    mlm_labels=None,
):
    return_dict = return_dict if return_dict is not None else cls.config.use_return_dict
    ori_input_ids = input_ids
    batch_size = input_ids.size(0)
    # Two dropout views of the same sentence
    num_sent = input_ids.size(1)
    if num_sent != 2:
        raise ValueError("Unsupervised training requires exactly two views per sentence.")

    mlm_outputs = None
    # Flatten input for encoding
    input_ids = input_ids.view((-1, input_ids.size(-1))) # (bs * num_sent, len)
    attention_mask = attention_mask.view((-1, attention_mask.size(-1))) # (bs * num_sent len)
    if token_type_ids is not None:
        token_type_ids = token_type_ids.view((-1, token_type_ids.size(-1))) # (bs * num_sent, len)

    # Get raw embeddings
    outputs = encoder(
        input_ids,
        attention_mask=attention_mask,
        token_type_ids=token_type_ids,
        position_ids=position_ids,
        head_mask=head_mask,
        inputs_embeds=inputs_embeds,
        output_attentions=output_attentions,
        output_hidden_states=True if cls.model_args.pooler_type in ['avg_top2', 'avg_first_last'] else False,
        return_dict=True,
    )

    # MLM auxiliary objective
    if mlm_input_ids is not None:
        mlm_input_ids = mlm_input_ids.view((-1, mlm_input_ids.size(-1)))
        mlm_outputs = encoder(
            mlm_input_ids,
            attention_mask=attention_mask,
            token_type_ids=token_type_ids,
            position_ids=position_ids,
            head_mask=head_mask,
            inputs_embeds=inputs_embeds,
            output_attentions=output_attentions,
            output_hidden_states=True if cls.model_args.pooler_type in ['avg_top2', 'avg_first_last'] else False,
            return_dict=True,
        )

    # Pooling
    pooler_output = cls.pooler(attention_mask, outputs)
    pooler_output = pooler_output.view((batch_size, num_sent, pooler_output.size(-1))) # (bs, num_sent, hidden)

    # If using "cls", we add an extra MLP layer
    # (same as BERT's original implementation) over the representation.
    if cls.pooler_type == "cls":
        pooler_output = cls.mlp(pooler_output)

    # Separate representation
    z1, z2 = pooler_output[:,0], pooler_output[:,1]

    if cls.model_args.loss_type == "simcse":
        cos_sim = cls.sim(z1.unsqueeze(1), z2.unsqueeze(0))
        labels = torch.arange(cos_sim.size(0)).long().to(cls.device)
        loss_fct = nn.CrossEntropyLoss()

        loss = loss_fct(cos_sim, labels)
    else:
        loss, cos_sim = cls.loss_fct(z1, z2)

    # Calculate loss for MLM
    if mlm_outputs is not None and mlm_labels is not None:
        mlm_labels = mlm_labels.view(-1, mlm_labels.size(-1))
        prediction_scores = cls.lm_head(mlm_outputs.last_hidden_state)
        masked_lm_loss = F.cross_entropy(
            prediction_scores.view(-1, cls.config.vocab_size),
            mlm_labels.view(-1),
        )
        loss = loss + cls.model_args.mlm_weight * masked_lm_loss

    if not return_dict:
        output = (cos_sim,) + outputs[2:]
        return ((loss,) + output) if loss is not None else output
    return SequenceClassifierOutput(
        loss=loss,
        logits=cos_sim,
        hidden_states=outputs.hidden_states,
        attentions=outputs.attentions,
    )


def sentemb_forward(
    cls,
    encoder,
    input_ids=None,
    attention_mask=None,
    token_type_ids=None,
    position_ids=None,
    head_mask=None,
    inputs_embeds=None,
    labels=None,
    output_attentions=None,
    output_hidden_states=None,
    return_dict=None,
):

    return_dict = return_dict if return_dict is not None else cls.config.use_return_dict

    outputs = encoder(
        input_ids,
        attention_mask=attention_mask,
        token_type_ids=token_type_ids,
        position_ids=position_ids,
        head_mask=head_mask,
        inputs_embeds=inputs_embeds,
        output_attentions=output_attentions,
        output_hidden_states=True if cls.pooler_type in ['avg_top2', 'avg_first_last'] else False,
        return_dict=True,
    )

    pooler_output = cls.pooler(attention_mask, outputs)
    if cls.pooler_type == "cls" and not cls.model_args.mlp_only_train:
        pooler_output = cls.mlp(pooler_output)

    if not return_dict:
        return (outputs[0], pooler_output) + outputs[2:]

    return BaseModelOutputWithPoolingAndCrossAttentions(
        pooler_output=pooler_output,
        last_hidden_state=outputs.last_hidden_state,
        hidden_states=outputs.hidden_states,
    )


class BertForCL(BertPreTrainedModel):
    _keys_to_ignore_on_load_missing = [r"position_ids"]

    def __init__(self, config, *model_args, **model_kargs):
        super().__init__(config)
        self.model_args = model_kargs["model_args"]
        self.bert = BertModel(config, add_pooling_layer=False)

        if self.model_args.do_mlm:
            self.lm_head = BertLMPredictionHead(config)

        cl_init(self, config)

    def forward(self,
        input_ids=None,
        attention_mask=None,
        token_type_ids=None,
        position_ids=None,
        head_mask=None,
        inputs_embeds=None,
        labels=None,
        output_attentions=None,
        output_hidden_states=None,
        return_dict=None,
        sent_emb=False,
        mlm_input_ids=None,
        mlm_labels=None,
    ):
        if sent_emb:
            return sentemb_forward(self, self.bert,
                input_ids=input_ids,
                attention_mask=attention_mask,
                token_type_ids=token_type_ids,
                position_ids=position_ids,
                head_mask=head_mask,
                inputs_embeds=inputs_embeds,
                labels=labels,
                output_attentions=output_attentions,
                output_hidden_states=output_hidden_states,
                return_dict=return_dict,
            )
        else:
            return cl_forward(self, self.bert,
                input_ids=input_ids,
                attention_mask=attention_mask,
                token_type_ids=token_type_ids,
                position_ids=position_ids,
                head_mask=head_mask,
                inputs_embeds=inputs_embeds,
                labels=labels,
                output_attentions=output_attentions,
                output_hidden_states=output_hidden_states,
                return_dict=return_dict,
                mlm_input_ids=mlm_input_ids,
                mlm_labels=mlm_labels,
            )



